const simulateLatency = () =>
  new Promise((resolve) => setTimeout(resolve, 300 + Math.random() * 300));

/**
 * Cited semantic search over past conversations using pgvector RAG.
 * @endpoint POST /functions/v1/search
 * @returns {Promise<{ answer: string | null, sources: Array }>}
 */
export async function searchConversations(query) {
  await simulateLatency();

  if (!query || !query.trim()) {
    return { answer: null, sources: [] };
  }

  const normalized = query.toLowerCase();

  if (normalized.includes('schema')) {
    return {
      answer:
        'The MindMate AI database schema is built on PostgreSQL v16 with tables for conversations, messages, memories, and pending_actions [1]. All vector embeddings use HNSW indexing with cosine distance for fast memory retrieval [2].',
      sources: [
        {
          id: 'src-1',
          conversationId: 'conv-1',
          conversationTitle: 'Database schema for MindMate',
          date: 'Today',
          excerpt:
            'CREATE TABLE public.conversations and public.messages with row-level security enabled and user isolation policies.',
          messageRange: 'Messages 2-4',
          score: 0.94,
        },
        {
          id: 'src-2',
          conversationId: 'conv-4',
          conversationTitle: 'Gemini embeddings dimensions',
          date: 'Yesterday',
          excerpt:
            'Using 768-dimension embeddings generated by text-embedding-004 with HNSW cosine indexes.',
          messageRange: 'Messages 1-3',
          score: 0.88,
        },
      ],
    };
  }

  // When no relevant chunks pass the similarity threshold, PRD & API_SHAPES require:
  return {
    answer: null,
    sources: [],
  };
}

